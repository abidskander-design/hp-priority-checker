"""Gerrit REST API helpers for OpenStack Review."""

from __future__ import annotations

import re
import requests

GERRIT_BASE = "https://review.opendev.org"


def _get(path: str, timeout: int = 15) -> dict | list:
    url = f"{GERRIT_BASE}{path}"
    r = requests.get(url, timeout=timeout)
    r.raise_for_status()
    # Gerrit prepends ")]}'\n" to prevent XSSI
    text = r.text
    if text.startswith(")]}'"):
        text = text[text.index("\n") + 1:]
    import json
    return json.loads(text)


def fetch_change(change_id: str) -> dict:
    """Return the full change detail from Gerrit REST.

    change_id may be a numeric Change-Id, the hash (Ixxxxxx), or project~branch~Id.
    """
    # Gerrit normalises all these to the same endpoint
    encoded = requests.utils.quote(change_id, safe="~")
    data = _get(
        f"/changes/{encoded}"
        "?o=DETAILED_ACCOUNTS"
        "&o=COMMIT_FOOTERS"
        "&o=CURRENT_REVISION"
        "&o=CURRENT_COMMIT"
        "&o=DETAILED_LABELS"
        "&o=MESSAGES"
        "&o=CURRENT_FILES"
    )
    return data


def fetch_patchset1_commit(change_id: str) -> dict | None:
    """Return the commit message + diff stats for patchset 1 specifically."""
    encoded = requests.utils.quote(change_id, safe="~")
    try:
        revs = _get(
            f"/changes/{encoded}/revisions?o=COMMIT_FOOTERS"
        )
        # revs is a dict of {sha: {_number: N, commit: {...}}}
        ps1_sha = None
        for sha, info in revs.items():
            if info.get("_number") == 1:
                ps1_sha = sha
                break
        if ps1_sha is None:
            return None
        commit = _get(f"/changes/{encoded}/revisions/{ps1_sha}/commit")
        return commit
    except Exception:
        return None


def extract_change_info(raw: dict) -> dict:
    """Flatten Gerrit change JSON to a plain dict consumed by FeatureExtractor."""
    project = raw.get("project", "")
    branch  = raw.get("branch", "")
    subject = raw.get("subject", "")
    change_num = str(raw.get("_number", ""))

    # Owner info
    owner = raw.get("owner", {})
    owner_id       = str(owner.get("_account_id", ""))
    owner_email    = owner.get("email", "")
    owner_username = owner.get("username", "")

    # Stats from current revision
    cur_rev = None
    revisions = raw.get("revisions", {})
    if revisions:
        cur_sha = raw.get("current_revision", "")
        cur_rev = revisions.get(cur_sha, {})

    insertions  = raw.get("insertions", 0) or 0
    deletions   = raw.get("deletions", 0) or 0
    topic       = raw.get("topic", "") or ""

    # Message count + recent human reviewer comments
    messages = raw.get("messages", [])
    msg_count = len(messages)

    recent_comments: list[str] = []
    for msg in messages:
        tag = msg.get("tag", "") or ""
        if tag.startswith("autogenerated"):
            continue
        author_info = msg.get("author", {})
        author_name = author_info.get("name") or author_info.get("username") or "Reviewer"
        text = (msg.get("message", "") or "").strip()
        if text and len(text) > 15:
            snippet = text[:300].replace("\n", " ")
            recent_comments.append(f"{author_name}: {snippet}")
    recent_comments = recent_comments[-5:]  # keep last 5 human comments

    # File list from current revision
    files = cur_rev.get("files", {}) if cur_rev else {}
    n_files = len(files)
    changed_files = list(files.keys())[:10]

    # Commit message from current revision's commit object
    commit_msg = ""
    commit_body = ""
    if cur_rev:
        commit_obj = cur_rev.get("commit", {})
        commit_msg = commit_obj.get("message", "")
        if commit_msg:
            lines = commit_msg.split("\n")
            # Skip first line (subject) and blank line, take the rest as body
            body_lines = [l for l in lines[2:] if l.strip()] if len(lines) > 2 else []
            commit_body = "\n".join(body_lines[:15]).strip()  # cap at 15 lines

    created  = raw.get("created", "")   # "2024-01-15 10:23:00.000000000"
    updated  = raw.get("updated", "")

    return {
        "change_id":      raw.get("id", change_num),
        "change_num":     change_num,
        "project":        project,
        "branch":         branch,
        "subject":        subject,
        "owner_id":       owner_id,
        "owner_email":    owner_email,
        "owner_username": owner_username,
        "insertions":     insertions,
        "deletions":      deletions,
        "topic":          topic,
        "n_messages":     msg_count,
        "n_files":        n_files,
        "commit_message": commit_msg,
        "commit_body":    commit_body,
        "changed_files":  changed_files,
        "recent_comments": recent_comments,
        "created":        created,
        "updated":        updated,
    }
