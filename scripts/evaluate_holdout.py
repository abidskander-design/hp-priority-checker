#!/usr/bin/env python3
"""Held-out (time-aware) evaluation of the deployed HP+ pipeline.

train_models.py fits and scores on the same data, so the train AUC stored in
backend/models/manifest.json is in-sample. This script evaluates the same
pipeline (same SubmissionFeatureBuilder features, same XGBoost settings via
train_models.make_model) on later, unseen changes, using the split of the
research study (rp_predict DataPreprocessor), per project:

    train = oldest 75% of changes created before 2024-01-01
    val   = newest 25% of changes created before 2024-01-01  (threshold choice)
    test  = all changes created on or after 2024-01-01

Thresholds (G-mean, F0.5) are chosen on val only and then applied to test.
The deployed models in backend/models/ are not modified.

Usage:
    python scripts/evaluate_holdout.py
Writes evaluation/holdout_results.csv and evaluation/holdout_results.md.
"""

from __future__ import annotations

import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import (average_precision_score, f1_score, matthews_corrcoef,
                             precision_score, recall_score, roc_auc_score)

from train_models import (DATA_CSV, PROJECTS, SHORT, SubmissionFeatureBuilder,
                          add_derived_columns, find_thresholds, make_model)

warnings.filterwarnings("ignore")

TRAIN_END    = pd.Timestamp("2024-01-01", tz="UTC")
VAL_FRACTION = 0.25
OUT_DIR      = Path(__file__).parent.parent / "evaluation"


def split(df_project: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    df_project = df_project.sort_values("created_ts")
    train_val = df_project[df_project["created_ts"] < TRAIN_END]
    test      = df_project[df_project["created_ts"] >= TRAIN_END]
    cut = int(len(train_val) * (1 - VAL_FRACTION))
    return train_val.iloc[:cut], train_val.iloc[cut:], test


def at_threshold(y: np.ndarray, prob: np.ndarray, thr: float) -> dict:
    pred = (prob >= thr).astype(int)
    return {
        "mcc":       matthews_corrcoef(y, pred),
        "precision": precision_score(y, pred, zero_division=0),
        "recall":    recall_score(y, pred, zero_division=0),
        "f1":        f1_score(y, pred, zero_division=0),
        "flagged":   int(pred.sum()),
    }


def evaluate_project(project: str, df_project: pd.DataFrame) -> dict:
    train, val, test = split(add_derived_columns(df_project))
    y_val  = val["hp_positive"].to_numpy(dtype=int)
    y_test = test["hp_positive"].to_numpy(dtype=int)

    n_pos = int(train["hp_positive"].sum())
    spw   = round((len(train) - n_pos) / max(n_pos, 1), 2)

    builder = SubmissionFeatureBuilder()
    X_train, y_train = builder.fit_transform(train)
    model = make_model(spw).fit(X_train, y_train)

    p_val  = model.predict_proba(builder.transform(val))[:, 1]
    p_test = model.predict_proba(builder.transform(test))[:, 1]
    thrs   = find_thresholds(y_val, p_val)

    row = {
        "project": SHORT[project],
        "n_train": len(train), "hp_train": n_pos,
        "n_val":   len(val),   "hp_val":   int(y_val.sum()),
        "n_test":  len(test),  "hp_test":  int(y_test.sum()),
        "roc_auc": roc_auc_score(y_test, p_test),
        "pr_auc":  average_precision_score(y_test, p_test),
        "hp_rate_test": y_test.mean(),
    }
    for name in ("gmean", "f05"):
        row[f"thr_{name}"] = thrs[name]
        for k, v in at_threshold(y_test, p_test, thrs[name]).items():
            row[f"{k}_{name}"] = v
    return row


def to_markdown(res: pd.DataFrame) -> str:
    mean = res.mean(numeric_only=True)
    lines = [
        "# Held-out evaluation of the deployed HP+ pipeline",
        "",
        "Same features and XGBoost settings as the deployed models; trained on",
        "changes before 2024-01-01 (thresholds chosen on the newest 25% of them),",
        "tested on all changes from 2024-01-01 on. Generated by",
        "`scripts/evaluate_holdout.py`.",
        "",
        "| Project | N test | HP+ test | ROC-AUC | PR-AUC | MCC (G-mean thr) | Prec | Rec | MCC (F0.5 thr) | Prec | Rec |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in res.iterrows():
        lines.append(
            f"| {r.project} | {r.n_test} | {r.hp_test} ({r.hp_rate_test:.1%}) | {r.roc_auc:.3f} | {r.pr_auc:.3f} "
            f"| {r.mcc_gmean:.3f} | {r.precision_gmean:.3f} | {r.recall_gmean:.3f} "
            f"| {r.mcc_f05:.3f} | {r.precision_f05:.3f} | {r.recall_f05:.3f} |")
    lines.append(
        f"| **mean** | | | **{mean.roc_auc:.3f}** | **{mean.pr_auc:.3f}** "
        f"| **{mean.mcc_gmean:.3f}** | {mean.precision_gmean:.3f} | {mean.recall_gmean:.3f} "
        f"| **{mean.mcc_f05:.3f}** | {mean.precision_f05:.3f} | {mean.recall_f05:.3f} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    print(f"Loading {DATA_CSV} …")
    df = pd.read_csv(DATA_CSV, low_memory=False)
    df["created_ts"] = pd.to_datetime(df["created_ts"], utc=True, errors="coerce")

    rows = []
    for project in PROJECTS:
        r = evaluate_project(project, df[df["project"] == project].copy())
        print(f"  {r['project']:10s} test={r['n_test']:5d} (HP+ {r['hp_test']:3d})  "
              f"AUC={r['roc_auc']:.3f}  PR-AUC={r['pr_auc']:.3f}  "
              f"MCC@gmean={r['mcc_gmean']:.3f}  MCC@f05={r['mcc_f05']:.3f}")
        rows.append(r)

    res = pd.DataFrame(rows)
    OUT_DIR.mkdir(exist_ok=True)
    res.to_csv(OUT_DIR / "holdout_results.csv", index=False, float_format="%.4f")
    (OUT_DIR / "holdout_results.md").write_text(to_markdown(res))
    print(f"\nWrote {OUT_DIR / 'holdout_results.csv'} and holdout_results.md")


if __name__ == "__main__":
    main()
